/*
 * The administrative map in force since 1 July 2025: no district level, each city holds its wards (phường),
 * communes (xã) and special zones (đặc khu) directly. TP. Hồ Chí Minh took in Bình Dương and Bà Rịa – Vũng Tàu;
 * TP. Cần Thơ took in Sóc Trăng and Hậu Giang. Coordinates are approximate centres, good enough for maps and
 * distances, not for boundaries.
 */

/** [official name, where it was before the merger, lat, lng] */
type WardRow = [string, string, number, number];

function city(slug: string, name: string, shortName: string, center: { lat: number; lng: number }, rows: WardRow[]): City {
  const bare = (n: string) => n.replace(/^(Phường|Xã|Đặc khu) /, "");
  // Names can meet once accents are dropped (Thanh An, Thạnh An) or a phường and a xã can share one. Phường are
  // given slugs first, so they keep the short form; the others add their kind, then their former area.
  const used = new Set<string>();
  const slugs = new Map<string, string>();
  const order = [...rows].sort((a, b) => Number(!a[0].startsWith("Phường")) - Number(!b[0].startsWith("Phường")));
  for (const [wName, formerArea] of order) {
    const short = slugify(bare(wName));
    const wSlug = [short, slugify(wName), `${short}-${slugify(formerArea)}`].find((s) => !used.has(s))!;
    used.add(wSlug);
    slugs.set(wName, wSlug);
  }
  const wards: Ward[] = rows.map(([wName, formerArea]) => ({ slug: slugs.get(wName)!, name: wName, citySlug: slug, formerArea }));
  return { slug, name, shortName, center, wards };
}

